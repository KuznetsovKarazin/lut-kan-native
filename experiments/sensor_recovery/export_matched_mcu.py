"""Deterministic MCU export of the predeclared matched-storage confirmation case."""
import gzip
import hashlib
import json
from pathlib import Path
import numpy as np
from calibration import make_sensor,calibration_case
from matched_adaptation import (static_models,initial_models,generate_stream,trajectory,
                                model_record,serialized_payload)

HERE=Path(__file__).resolve().parent
OUT=HERE/"mcu"
SEED=2026110801
CHECKPOINTS=(0,127,128,160,192,256,320,384)
STATIC_NAMES=("lut_float32","lut_int16","cubic_compact","cubic_horner")
ONLINE_NAMES=("lut_nlms","lut_projected_nlms","cubic_nlms","cubic_projected_nlms")
MODES=("none","step","ramp")


def f32(x):
    s=format(float(np.float32(x)),".9g")
    return s+("f" if "." in s or "e" in s else ".0f")


def array(name,values):
    a=np.asarray(values,np.float32)
    dims="".join(f"[{n}]" for n in a.shape)
    def block(v):
        if v.ndim==1:return "{"+", ".join(f32(x) for x in v)+"}"
        return "{\n"+",\n".join(block(row) for row in v)+"\n}"
    return f"static const float {name}{dims} MATCHED_FLASH = "+block(a)+";"


def export():
    case=calibration_case(make_sensor("ntc_frontend",0,SEED),75,0,SEED)
    models={name:m for cap,name,m in static_models(case) if cap==144 and name in STATIC_NAMES}
    initial=initial_models(case);tr=case["transform"]
    transform="{"+", ".join(f32(v) for v in vars(tr).values())+"}"
    h=['// Generated by export_matched_mcu.py. Synthetic confirmation fixture; no sensor acquisition.',
       '#pragma once','#include "matched_kernels.h"',
       '#ifndef MATCHED_FLASH','#define MATCHED_FLASH','#endif',
       '#ifndef MATCHED_INITIAL_FLASH','#define MATCHED_INITIAL_FLASH','#endif',
       '#define MATCHED_GRID_N 401','#define MATCHED_STEPS 384','#define MATCHED_CHECKS 8']
    for name in STATIC_NAMES:
        m=models[name];sym="matched_"+name
        if name=="lut_int16":
            vals="{"+", ".join(str(int(x)) for x in m.values)+"}"
            h.append(f"static const Matched::Int16Model {sym} = {{{vals},{f32(m.scale)},{f32(m.offset)},{transform}}};")
        else:
            values=m.values if name=="lut_float32" else m.coefficients if name=="cubic_compact" else m.pieces.reshape(-1)
            vals="{"+", ".join(f32(x) for x in values)+"}"
            h.append(f"static const Matched::FloatModel {sym} = {{{vals},{transform}}};")
    for name in ("lut","cubic"):
        vals="{"+", ".join(f32(x) for x in initial[name].coefficients)+"}"
        h.append(f"static const Matched::FloatModel matched_initial_{name} MATCHED_INITIAL_FLASH = {{{vals},{transform}}};")
    adc=case["x_noisy"]*tr.x_half+tr.x_mid
    truth=case["y_test"]*tr.y_half+tr.y_mid
    predictions=np.array([models[name].predict(case["x_noisy"])*tr.y_half+tr.y_mid for name in STATIC_NAMES])
    streams=[];states=[];metrics=[];stream_adc=[];stream_ref=[];final_adc=[]
    for mode in MODES:
        stream=generate_stream(case,0,75,mode,SEED)
        stream_adc.append(stream["x"]*tr.x_half+tr.x_mid)
        stream_ref.append(stream["y"]*tr.y_half+tr.y_mid)
        final_adc.append(stream["tests"][384]["x"]*tr.x_half+tr.x_mid)
        runs=[trajectory(initial,stream,name,.5,retain=True) for name in ONLINE_NAMES]
        states.append([[next(s["state"]["coefficients"] for s in r["snapshots"] if s["t"]==t) for t in CHECKPOINTS] for r in runs])
        metrics.append([[r["snapshots"][-1]["after"][k] for k in ("mae","rmse","max_abs")] for r in runs])
        streams.append(dict(mode=mode,adc=np.asarray(stream_adc[-1],np.float32).tolist(),
            reference=np.asarray(stream_ref[-1],np.float32).tolist(),
            final_adc=np.asarray(final_adc[-1],np.float32).tolist(),
            reference_states=states[-1],reference_final_metrics=metrics[-1]))
    h.append('#ifndef MATCHED_FOOTPRINT')
    for name,values in [("matched_adc",adc),("matched_truth",truth),("matched_expected",predictions),
        ("matched_stream_adc",stream_adc),("matched_stream_reference",stream_ref),
        ("matched_final_adc",final_adc),("matched_reference_states",states),
        ("matched_reference_metrics",metrics)]:h.append(array(name,values))
    h.append('static const uint16_t matched_checkpoints[8] = {'+','.join(map(str,CHECKPOINTS))+'};')
    h.append('#endif')
    header="\n".join(h)+"\n"
    (OUT/"include/matched_fixture.h").write_text(header)
    data=dict(seed=SEED,scenario="ntc_frontend",unit=0,repeat=0,budget=75,checkpoints=CHECKPOINTS,
        static_names=STATIC_NAMES,online_names=ONLINE_NAMES,transform=vars(tr),
        adc=np.asarray(adc,np.float32).tolist(),truth=np.asarray(truth,np.float32).tolist(),
        static_expected=np.asarray(predictions,np.float32).tolist(),streams=streams)
    (OUT/"matched_host_reference.json").write_text(json.dumps(data,indent=2)+"\n")
    manifest=dict(seed=SEED,scenario="ntc_frontend",unit=0,repeat=0,budget=75,suite="matched_adaptation_v1",
        static_names=STATIC_NAMES,online_names=ONLINE_NAMES,modes=MODES,checkpoints=CHECKPOINTS,
        model_payload_bytes=144,persistent_update_bytes=148,pava_workspace_bytes=160,
        parity_gate_C=.002,physical_sensor_measurements=False,
        reference_arithmetic="original float64-intermediate host trajectory; target uses float32 throughout",
        fixture_input_encoding="raw ADC ratios and physical reference quantities rounded to float32",
        models={name:dict(record=model_record(m),payload_sha256=hashlib.sha256(serialized_payload(m)).hexdigest()) for name,m in models.items()},
        initial_models={name:model_record(initial[name]) for name in ("lut","cubic")},
        fixture_sha256=hashlib.sha256(header.encode()).hexdigest(),
        reference_sha256=hashlib.sha256((OUT/"matched_host_reference.json").read_bytes()).hexdigest())
    (OUT/"matched_manifest.json").write_text(json.dumps(manifest,indent=2)+"\n")
    (OUT/"include/matched_identity.h").write_text('#pragma once\n#define MATCHED_FIXTURE_SHA256 "'+manifest['fixture_sha256']+'"\n')
    return manifest


if __name__=="__main__":
    m=export();print(json.dumps({k:m[k] for k in ("suite","fixture_sha256","reference_sha256")}))
