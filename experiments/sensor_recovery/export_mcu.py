"""Export the fixed confirmation fixture; never select it by test results."""
import hashlib,json
from pathlib import Path
import numpy as np
from calibration import make_sensor,calibration_case,fit_physics,fit_selected,EncodedLUT
from robust import fit_shape,encode_shape

HERE=Path(__file__).resolve().parent
def flt(x):
    s=format(float(np.float32(x)),".9g")
    if "." not in s and "e" not in s:s+=".0"
    return s+"f"

def main():
    c=calibration_case(make_sensor("ntc_frontend",0,20261108),75,0,20261108)
    tr=c["transform"];x,y=c["x"],c["y"];t,v=c["train_idx"],c["val_idx"]
    args=x[t],y[t],x[v],y[v],tr,"ntc_frontend"
    physics=fit_physics(x,y,tr,"ntc_frontend")
    poly=fit_selected("poly",*args);cubic=fit_selected("cubic",*args,n_coeff=16)
    kan=fit_selected("kan_edge",*args,n_coeff=16)
    uniform,uk=fit_shape(*args,32,True,False)
    irregular,ik=fit_shape(*args,16,True,True)
    models=[("physics",physics),("polynomial",poly),("cubic16",cubic),("kan16",kan)]
    for fmt in ("float32","int16","uint8"):
        models.append(("uniform32_"+fmt,encode_shape(uniform,uk,fmt)))
    models.append(("nonuniform16_int16",encode_shape(irregular,ik,"int16",True)))
    out=HERE/"mcu"/"include";out.mkdir(parents=True,exist_ok=True)
    lines=["// Generated by export_mcu.py: synthetic fixture, not measured sensor data.","#pragma once", "#include <stdint.h>",
           "#ifndef FIXTURE_FLASH", "#define FIXTURE_FLASH", "#endif", "#define FIXTURE_N 401", "#define SENSOR_MODEL_COUNT 8"]
    def array(name,values,ctype="float",flash=False):
        body=[flt(z) for z in values] if ctype=="float" else [str(int(z)) for z in values]
        lines.append(f"static const {ctype} {name}[{len(body)}]"+(" FIXTURE_FLASH" if flash else "")+" = {")
        lines.extend("  "+", ".join(body[i:i+8])+"," for i in range(0,len(body),8));lines.append("};")
    for key,value in vars(tr).items():lines.append(f"static const float {key} = {flt(value)};")
    array("physics_c",physics.coefficients);array("poly_c",poly.coefficients)
    lines.append(f"#define POLY_N {len(poly.coefficients)}")
    array("cubic_c",cubic.coefficients);array("kan_c",kan.coefficients)
    array("lut_f32",uniform.coefficients)
    encs={fmt:EncodedLUT.from_model(uniform,fmt) for fmt in ("int16","uint8")}
    for fmt,e in encs.items():
        array("lut_"+fmt,e.values,"int16_t" if fmt=="int16" else "uint8_t")
        lines.extend([f"static const float {fmt}_scale = {flt(e.scale)};",f"static const float {fmt}_offset = {flt(e.offset)};"])
    ie=EncodedLUT.from_model(irregular,"int16")
    array("irregular_values",ie.values,"int16_t");array("irregular_knots",ik)
    lines.extend([f"static const float irregular_scale = {flt(ie.scale)};",f"static const float irregular_offset = {flt(ie.offset)};"])
    adc=tr.dx(c["x_noisy"]).astype(np.float32)
    # The exact same rounded ADC inputs are used for firmware and host parity.
    array("fixture_adc",adc,flash=True);array("fixture_truth",tr.dy(c["y_test"]),flash=True)
    array("expected_0",adc,flash=True)
    modelmeta=[]
    for i,(name,m) in enumerate(models,1):
        expected=tr.dy(m.predict(tr.nx(adc)))
        array(f"expected_{i}",expected,flash=True)
        modelmeta.append(dict(id=i,name=name,payload_bytes=m.payload_bytes(),hyper=m.hyper))
    header="\n".join(lines)+"\n";(out/"fixture.h").write_text(header,encoding="utf8")
    manifest=dict(seed=20261108,scenario="ntc_frontend",unit=0,repeat=0,budget=75,
        reference_sha256=c["reference_sha256"],header_sha256=hashlib.sha256(header.encode()).hexdigest(),
        transform=vars(tr),models=modelmeta,physical_measurements=False,parity_tolerance_degC=.002)
    (HERE/"mcu"/"fixture_manifest.json").write_text(json.dumps(manifest,indent=2)+"\n")
    # A portable host-test fixture also covers clamps and all interval boundaries.
    extra_adc=tr.dx(np.r_[-1.5,-1,np.linspace(-1,1,1001),1,1.5]).astype(np.float32)
    expectations={name:tr.dy(m.predict(tr.nx(extra_adc))).tolist() for name,m in models}
    manifest["parity_adc"]=extra_adc.tolist();manifest["parity_expected"]=expectations
    (HERE/"mcu"/"host_parity.json").write_text(json.dumps(manifest)+"\n")
    print("Exported fixed NTC frontend fixture: 8 models, 401 ADC/target pairs.")

if __name__=="__main__":main()
